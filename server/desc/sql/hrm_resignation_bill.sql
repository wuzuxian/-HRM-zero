CREATE TABLE `hrm_resignation_bill` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `uuid` varchar(36) NOT NULL UNIQUE,
  `create_time` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `bill_no` varchar(32) NOT NULL COMMENT '单据编号 HR204-YYYYMMDD+5位流水',
  `status` varchar(16) NOT NULL DEFAULT 'unsubmitted' COMMENT '单据状态 unsubmitted/approving/approved/rejected/revoked',
  `employee_uuid` varchar(36) NOT NULL DEFAULT '' COMMENT '员工档案 uuid（HRM-03）',
  `employee_no` varchar(50) NOT NULL DEFAULT '' COMMENT '员工工号（快照）',
  `employee_name` varchar(100) NOT NULL DEFAULT '' COMMENT '员工姓名（快照）',
  `org_uuid` varchar(36) NOT NULL DEFAULT '' COMMENT '员工所属部门（组织 uuid，快照）',
  `company_uuid` varchar(36) NOT NULL DEFAULT '' COMMENT '员工所属公司（组织 uuid，快照）',
  `position` varchar(100) NOT NULL DEFAULT '' COMMENT '职位（快照）',
  `post` varchar(100) NOT NULL DEFAULT '' COMMENT '职务（快照）',
  `resign_type` varchar(16) NOT NULL DEFAULT 'voluntary' COMMENT '离职类型 voluntary=自愿离职 involuntary=被动离职 contract_end=合同到期 retirement=退休',
  `resign_reason` varchar(500) NOT NULL DEFAULT '' COMMENT '离职原因',
  `apply_date` varchar(10) NOT NULL DEFAULT '' COMMENT '申请日期 YYYY-MM-DD',
  `resign_date` varchar(10) NOT NULL DEFAULT '' COMMENT '离职日期 YYYY-MM-DD（定时任务在当日统一置离职）',
  `last_work_date` varchar(10) NOT NULL DEFAULT '' COMMENT '最后工作日期 YYYY-MM-DD',
  `handover_person` varchar(100) NOT NULL DEFAULT '' COMMENT '交接人',
  `salary_settle_date` varchar(10) NOT NULL DEFAULT '' COMMENT '薪资结算日期 YYYY-MM-DD',
  `applied` bigint NOT NULL DEFAULT 0 COMMENT '离职生效是否已完成 1=是 0=否（幂等标记，定时任务据此扫描）',
  `create_by` varchar(36) NOT NULL DEFAULT '' COMMENT '创建人（申请人）用户 uuid',
  `creator_name` varchar(100) NOT NULL DEFAULT '' COMMENT '申请人姓名（快照）',
  PRIMARY KEY (`id`),
  KEY `idx_hrm_resignation_bill_status` (`status`, `applied`),
  KEY `idx_hrm_resignation_bill_employee` (`employee_uuid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
