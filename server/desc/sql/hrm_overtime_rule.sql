CREATE TABLE `hrm_overtime_rule` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `uuid` varchar(36) NOT NULL UNIQUE,
  `create_time` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `rule_name` varchar(100) NOT NULL COMMENT '规则名称',
  `workday_approval_required` bigint NOT NULL DEFAULT 1 COMMENT '工作日需审批 1=需审批 0=免审批',
  `workday_punch_required` bigint NOT NULL DEFAULT 1 COMMENT '工作日需打卡 1=需打卡 0=免打卡',
  `workday_comp_multiplier` decimal(5,2) NOT NULL DEFAULT 1 COMMENT '工作日调休倍数（1=1:1）',
  `restday_approval_required` bigint NOT NULL DEFAULT 1 COMMENT '休息日需审批 1=需审批 0=免审批',
  `restday_punch_required` bigint NOT NULL DEFAULT 1 COMMENT '休息日需打卡 1=需打卡 0=免打卡',
  `restday_comp_multiplier` decimal(5,2) NOT NULL DEFAULT 1 COMMENT '休息日调休倍数',
  `holiday_approval_required` bigint NOT NULL DEFAULT 1 COMMENT '法定节假日需审批 1=需审批 0=免审批',
  `holiday_punch_required` bigint NOT NULL DEFAULT 1 COMMENT '法定节假日需打卡 1=需打卡 0=免打卡',
  `holiday_comp_multiplier` decimal(5,2) NOT NULL DEFAULT 1 COMMENT '法定节假日调休倍数',
  `min_unit_minutes` bigint NOT NULL DEFAULT 30 COMMENT '最小计算单位（分钟，默认30分钟）',
  `monthly_limit_hours` decimal(5,1) NOT NULL DEFAULT 0 COMMENT '月上限（小时，0=不限制）',
  `group_uuids` varchar(2000) NOT NULL DEFAULT '' COMMENT '使用的考勤组（逗号分隔 hrm_attendance_group.uuid，空=全部考勤组兜底规则）',
  `org_uuid` varchar(36) NOT NULL DEFAULT '' COMMENT '组织默认加班规则所属组织（hrm_org.uuid，空=全局默认规则）',
  `status` varchar(1) NOT NULL DEFAULT '1' COMMENT '状态 1=启用 0=停用',
  `remark` varchar(500) NOT NULL DEFAULT '',
  PRIMARY KEY (`id`),
  KEY `idx_hrm_overtime_rule_org_uuid` (`org_uuid`),
  KEY `idx_hrm_overtime_rule_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
