CREATE TABLE `hrm_leave_bill` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `uuid` varchar(36) NOT NULL UNIQUE,
  `create_time` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `bill_no` varchar(32) NOT NULL COMMENT '单据编号 HR205-YYYYMMDD+5位流水',
  `status` varchar(16) NOT NULL DEFAULT 'unsubmitted' COMMENT '单据状态 unsubmitted/approving/approved/rejected/revoked',
  `employee_uuid` varchar(36) NOT NULL DEFAULT '' COMMENT '员工档案 uuid（HRM-03）',
  `employee_no` varchar(50) NOT NULL DEFAULT '' COMMENT '员工工号（快照）',
  `employee_name` varchar(100) NOT NULL DEFAULT '' COMMENT '员工姓名（快照）',
  `org_uuid` varchar(36) NOT NULL DEFAULT '' COMMENT '员工所属部门（组织 uuid，快照）',
  `org_name` varchar(100) NOT NULL DEFAULT '' COMMENT '部门名称（快照，demo 列：部门）',
  `leave_type_code` varchar(50) NOT NULL COMMENT '假期类型编码 (hrm_leave_type.type_code)',
  `leave_type_name` varchar(50) NOT NULL DEFAULT '' COMMENT '假期类型名称（快照）',
  `plan_start_time` varchar(19) NOT NULL DEFAULT '' COMMENT '预计开始时间 YYYY-MM-DD HH:MM:SS',
  `plan_end_time` varchar(19) NOT NULL DEFAULT '' COMMENT '预计结束时间 YYYY-MM-DD HH:MM:SS',
  `plan_days` decimal(6,1) NOT NULL DEFAULT 0 COMMENT '预计天数（自动计算，0.5 天步进口径）',
  `reason` varchar(500) NOT NULL DEFAULT '' COMMENT '请假事由',
  `actual_start_time` varchar(19) NOT NULL DEFAULT '' COMMENT '实际开始时间（销假回填）YYYY-MM-DD HH:MM:SS',
  `actual_end_time` varchar(19) NOT NULL DEFAULT '' COMMENT '实际结束时间（销假回填）YYYY-MM-DD HH:MM:SS',
  `actual_days` decimal(6,1) NOT NULL DEFAULT 0 COMMENT '实际天数（销假自动计算；余额差额按其冲回）',
  `settled` bigint NOT NULL DEFAULT 0 COMMENT '销假是否已完成 1=是 0=否（幂等标记）',
  `create_by` varchar(36) NOT NULL DEFAULT '' COMMENT '创建人（申请人）用户 uuid',
  `creator_name` varchar(100) NOT NULL DEFAULT '' COMMENT '申请人姓名（快照）',
  PRIMARY KEY (`id`),
  KEY `idx_hrm_leave_bill_status` (`status`, `settled`),
  KEY `idx_hrm_leave_bill_employee` (`employee_uuid`),
  KEY `idx_hrm_leave_bill_type` (`leave_type_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
